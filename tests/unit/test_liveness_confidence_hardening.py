def test_pb2_generated_files_never_unwired_or_dead(tmp_path):
    _write(tmp_path, {
        "pyproject.toml": _PYPROJECT,
        "pkg/__init__.py": "",
        "pkg/main.py": "def main():\n    return 0\n",
        "proto/llm_pb2.py": _PB2_HEADER + "DESCRIPTOR = None\n",
        "proto/llm_pb2_grpc.py": (
            _PB2_GRPC_HEADER
            + "class LlmStub:\n"
            + "    def Generate(self, request):\n"
            + "        return request\n"
        ),
        "proto/wisdev.pb.go": (
            "// Code generated by protoc-gen-go. DO NOT EDIT.\n"
            "package proto\n\n"
            "type Wisdev struct{}\n"
        ),
    })
    _commit(tmp_path)
    graph = build_code_graph(tmp_path)
    for gen in ("proto/llm_pb2.py", "proto/llm_pb2_grpc.py", "proto/wisdev.pb.go"):
        assert gen not in graph.unwired_candidates, graph.unwired_candidates
        assert gen not in graph.unreachable_files, graph.unreachable_files
    assert not any(
        d.path.startswith("proto/") for d in graph.dead_code
    ), [(d.id, d.confidence) for d in graph.dead_code if d.path.startswith("proto/")]


