def test_shard_carries_content_exemption_and_backfills(tmp_path):
    """Incremental shard path must agree with the full build — including for
    pre-upgrade shards persisted without the new key (disk backfill)."""
    from devcouncil.indexing.graph.build import extract_all
    from devcouncil.indexing.graph.liveness import (
        build_liveness_shard,
        file_liveness_from_shards,
    )

    _write(tmp_path, {
        "pyproject.toml": _PYPROJECT,
        "pkg/__init__.py": "",
        "pkg/main.py": "def main():\n    return 0\n",
        "go.mod": "module example.com/app\n\ngo 1.21\n",
        "internal/assets/embed.go": (
            "package assets\n\n"
            'import "embed"\n\n'
            "//go:embed all:dist\n"
            "var Dist embed.FS\n"
        ),
        "stray/orphan.py": "value = 1\n",
    })
    _commit(tmp_path)
    files = [
        "pkg/__init__.py",
        "pkg/main.py",
        "internal/assets/embed.go",
        "stray/orphan.py",
    ]
    extractions = extract_all(tmp_path, files)
    shards = {
        path: build_liveness_shard(tmp_path, ext) for path, ext in extractions.items()
    }
    assert shards["internal/assets/embed.go"]["content_exemption"] == "side_effect"
    assert shards["stray/orphan.py"]["content_exemption"] is None

    _roots, unwired, _unreach, _unrel = file_liveness_from_shards(
        files, [], shards,
        root=tmp_path,
        entry_roots=["pkg/main.py"],
        production_entry_roots=["pkg/main.py"],
    )
    assert "internal/assets/embed.go" not in unwired, unwired
    assert "stray/orphan.py" in unwired, unwired

    # Pre-upgrade shards without the key: backfill from disk, same verdicts.
    legacy_shards = {
        path: {k: v for k, v in shard.items() if k != "content_exemption"}
        for path, shard in shards.items()
    }
    _roots, unwired_legacy, _unreach, _unrel = file_liveness_from_shards(
        files, [], legacy_shards,
        root=tmp_path,
        entry_roots=["pkg/main.py"],
        production_entry_roots=["pkg/main.py"],
    )
    assert unwired_legacy == unwired


def test_stress_synthetic_repo_precision(tmp_path):
    """~165-file repo mixing every known-live shape across Python/Go/JS.

    Precision contract: zero known-live files at unwired, zero extracted-tier
    dead symbols outside the planted dead set — while every plant is caught.
    """
    files: dict[str, str] = {
        "pyproject.toml": (
            '[project]\nname="t"\nversion="0"\n[project.scripts]\ncli="app.cli:main"\n'
        ),
        "app/__init__.py": "",
        "go.mod": "module example.com/app\n\ngo 1.21\n",
    }

    n_mods, n_dead = 60, 15
    imports, calls = [], []
    planted_dead = set()
    for i in range(n_mods):
        body = f"def use_{i}():\n    return {i}\n"
        if i < n_dead:
            body += f"def dead_fn_{i}():\n    return {i}\n"
            planted_dead.add(f"app/mod_{i}.py::dead_fn_{i}")
        files[f"app/mod_{i}.py"] = body
        imports.append(f"from app.mod_{i} import use_{i}")
        calls.append(f"    use_{i}()")
    files["app/cli.py"] = (
        "\n".join(imports) + "\ndef main():\n" + "\n".join(calls) + "\n    return 0\n"
    )

    # Generated stubs (Python + Go).
    for i in range(12):
        files[f"gen/g{i}_pb2.py"] = _PB2_HEADER + "DESCRIPTOR = None\n"
    for i in range(8):
        files[f"gen/g{i}_pb2_grpc.py"] = (
            _PB2_GRPC_HEADER
            + f"class Stub{i}:\n    def Call{i}(self, request):\n        return request\n"
        )
    for i in range(10):
        files[f"goproto/p{i}.pb.go"] = (
            "// Code generated by protoc-gen-go. DO NOT EDIT.\n"
            f"package goproto\n\ntype P{i} struct{{}}\n"
        )

    # Go side-effect carriers.
    for i in range(5):
        files[f"goapp/embed_{i}.go"] = (
            f"package goapp\n\nimport \"embed\"\n\n//go:embed all:dist{i}\nvar D{i} embed.FS\n"
        )
        files[f"goapp/load_{i}.go"] = (
            f"package goapp\n\nimport \"os\"\n\nfunc init() {{\n"
            f'\tos.Setenv("K{i}", "1")\n}}\n'
        )

    # Externally-launched entry scripts (__main__ guard).
    for i in range(10):
        files[f"tools_rt/app_{i}.py"] = (
            f"def serve_{i}():\n    return {i}\n\n"
            f'if __name__ == "__main__":\n    serve_{i}()\n'
        )

    # Launcher-file references: Dockerfile + Procfile.
    files["svc/Dockerfile"] = "FROM python:3.12-slim\n" + "".join(
        f"RUN python job_{i}.py\n" for i in range(5)
    )
    for i in range(5):
        files[f"svc/job_{i}.py"] = f"def job_{i}():\n    return {i}\njob_{i}()\n"
    files["svc2/__init__.py"] = ""
    files["Procfile"] = "".join(
        f"q{i}: python -m svc2.q_{i}\n" for i in range(5)
    )
    for i in range(5):
        files[f"svc2/q_{i}.py"] = f"def loop_{i}():\n    return {i}\nloop_{i}()\n"

    # Barrel packages.
    for i in range(5):
        files[f"lib_{i}/__init__.py"] = (
            f"from .impl import f_{i}\n__all__ = ['f_{i}']\n"
        )
        files[f"lib_{i}/impl.py"] = f"def f_{i}():\n    return {i}\n"

    # JS wired from src/index.js (conventional main seed).
    js_imports = []
    for i in range(20):
        files[f"src/w_{i}.js"] = f"export function work_{i}() {{ return {i} }}\n"
        js_imports.append(f"import {{ work_{i} }} from './w_{i}.js';")
    files["src/index.js"] = "\n".join(js_imports) + "\n"

    # Planted orphans — the only files that SHOULD be unwired.
    planted_orphans = set()
    for i in range(6):
        files[f"stray/orphan_{i}.py"] = f"value_{i} = {i}\n"
        planted_orphans.add(f"stray/orphan_{i}.py")

    _write(tmp_path, files)
    _commit(tmp_path)
    graph = build_code_graph(tmp_path)

    assert set(graph.unwired_candidates) == planted_orphans, (
        sorted(set(graph.unwired_candidates) ^ planted_orphans)
    )

    extracted = {
        d.id for d in graph.dead_code if d.confidence == Confidence.EXTRACTED
    }
    assert extracted == planted_dead, sorted(extracted ^ planted_dead)

    # Generated code must not surface at any tier.
    assert not any(
        d.path.startswith(("gen/", "goproto/")) for d in graph.dead_code
    ), [d.id for d in graph.dead_code if d.path.startswith(("gen/", "goproto/"))]


